declare(strict_types=1);

namespace Dotclear\Helper\Html\Form;

use Exception;

/**
 * @class Capture
 * @brief HTML Forms capture (capture echo) creation helpers
 */
class Capture extends Component
{
    /**
     * @var string DEFAULT_ELEMENT
     */
    private const DEFAULT_ELEMENT = '';

    /**
     * Capture buffer
     */
    private string $capture = '';

    /**
     * Constructs a new instance.
     *
     * @param      callable         $method     The method
     * @param      array<mixed>     $arguments  The arguments
     */
    public function __construct(callable $method, array $arguments = [])
    {
        parent::__construct(self::class, self::DEFAULT_ELEMENT);

        // Save current buffer level
        $bufferLevel = ob_get_level();

        try {
            // Start to capture output
            ob_start();

            // Call given method with its arguments
            $method(...$arguments);

            // Flush any buffers opened by the method in the capture buffer
            while (ob_get_level() > $bufferLevel + 1) {
                $nestedLevel = ob_get_level();
                $buffer      = ob_get_clean();
                if (ob_get_level() >= $nestedLevel) {
                    break;
                }

                if ($buffer !== false) {
                    echo $buffer;
                }
            }

            // Get final output generated by the method
            if (ob_get_level() === $bufferLevel + 1) {
                $this->capture = (string) ob_get_contents();
            }
        } catch (Exception) {
            // Will return en empty capture
        } finally {
            // Restore the saved buffer level and stop capturing output
            while (ob_get_level() > $bufferLevel) {
                $currentLevel = ob_get_level();
                ob_end_clean();
                if (ob_get_level() >= $currentLevel) {
                    break;
                }
            }
        }
    }

    /**
     * Renders the HTML component.
     */
    public function render(): string
    {
        return $this->capture;
    }

    /**
     * Gets the default element.
     *
     * @return     string  The default element.
     */
    public function getDefaultElement(): string
    {
        return self::DEFAULT_ELEMENT;
    }
}
